"""Build a beta and publish it as a GitHub pre-release on gismya/deluge-generative (spec §22.4).

Checks the pack first (`make_pack.py --check`: pack/ is what the script writes, which pack/LICENSES.md's CC0 rests
on; `check_pack_velocity.py`: every preset answers velocity) and refuses on a failure. Then runs `./dbt build
release`, zips the committed `pack/` tree (laid out as on the card, spec §18.1, with LICENSES.md under GENERATIVE/),
and attaches both to a new pre-release. Run it from the repo, on the commit to release, with that commit pushed to
origin:

    python3 scripts/generative/beta_release.py --dry-run          # check, build and zip into build/beta-release/ only
    python3 scripts/generative/beta_release.py --name "Beta 1"    # also publish, as "Generative Beta 1"

Without --name the release is named after the commit (generative-beta-<sha>).

Stdlib only.
"""

import argparse
import glob
import io
import os
import re
import shutil
import subprocess
import sys
import zipfile

FORK = "gismya/deluge-generative"
OUT_DIR = os.path.join("build", "beta-release")
PREFIX = "beta-release: "
# Where the pack's licence file goes on the card: GENERATIVE/ is the pack's own folder (spec §18.1).
LICENCE_ON_CARD = "GENERATIVE/LICENSES.md"
PACK_CHECKS = (
    ("scripts/generative/make_pack.py", "--check"),
    ("scripts/generative/check_pack_velocity.py",),
)
NOTES = """Generative beta built from {sha}.

Install: copy the .bin to the top level of the SD card (remove any other .bin there), then hold SHIFT while powering \
on. Unzip the pack zip onto the card root.

Generative mode: in Song view (from a clip, press SONG first), press SHIFT+SONG to open GENERATIVE, then PERFORM. \
PERFORM FROM opens: pick GENRE, then TECHNO, then ACID, MELODIC, DUB or DETROIT, then OK at DISCARD SONG?. Perform \
builds its song while yours plays on, then swaps in stopped: press PLAY.

Only the Techno subgenres (Acid, Melodic, Dub and Detroit techno) are in this beta; the other genres come in later \
betas.

The pack's files are generated by scripts/generative/make_pack.py and released under CC0 1.0 \
(GENERATIVE/LICENSES.md on the card): use them in anything, no credit needed."""


def log(msg):
    print(PREFIX + msg, flush=True)


def fail(msg):
    sys.exit(PREFIX + msg)


def git(*args):
    return subprocess.run(
        ["git", *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def check_pack():
    """Runs each pack check; refuses to go on if one fails."""
    for script, *args in PACK_CHECKS:
        if subprocess.run([sys.executable, script, *args], check=False).returncode != 0:
            fail(
                " ".join([script, *args]) + " failed: fix the pack before releasing it"
            )


def build_firmware():
    subprocess.run(["./dbt", "build", "release"], check=True)
    bins = glob.glob(os.path.join("build", "Release", "deluge*.bin"))
    if not bins:
        fail("the build made no build/Release/deluge*.bin")
    return max(bins, key=os.path.getmtime)


def zip_pack(sha, path):
    """Zip pack/ as committed at sha, with paths relative to the card root and LICENSES.md under GENERATIVE/."""
    archive = subprocess.run(
        ["git", "archive", "--format=zip", f"{sha}:pack"],
        capture_output=True,
        check=False,
    )
    with zipfile.ZipFile(path, "w") as out:
        if archive.returncode != 0:
            log("no pack/ in this commit, so the pack zip is empty")
            return
        with zipfile.ZipFile(io.BytesIO(archive.stdout)) as pack:
            for info in pack.infolist():
                data = pack.read(info)
                if info.filename == "LICENSES.md":
                    info.filename = LICENCE_ON_CARD
                out.writestr(info, data)


def publish(tag, title, sha, assets):
    # The repo is fixed and passed explicitly, so neither origin nor gh's default
    # repo can redirect the release. GH_REPO is dropped too, in case a gh version
    # ever lets it win over --repo.
    env = {k: v for k, v in os.environ.items() if k != "GH_REPO"}
    notes = NOTES.format(sha=sha)
    subprocess.run(
        [
            "gh",
            "release",
            "create",
            tag,
            *assets,
            "--repo",
            FORK,
            "--target",
            sha,
            "--prerelease",
            "--title",
            title,
            "--notes",
            notes,
        ],
        check=True,
        env=env,
    )


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="build and zip, but publish nothing"
    )
    parser.add_argument(
        "--name",
        help='the release\'s name, e.g. "Beta 1": titles it "Generative Beta 1" and tags it generative-beta-1 '
        "(default: the commit's short SHA)",
    )
    args = parser.parse_args(argv)

    os.chdir(git("rev-parse", "--show-toplevel"))
    sha = git("rev-parse", "HEAD")
    short_sha = sha[:9]
    if args.name:
        slug = re.sub(r"[^a-z0-9]+", "-", args.name.lower()).strip("-")
        if not slug:
            fail(f"--name {args.name!r} has no letters or digits to tag it with")
        tag = "generative-" + slug
        title = "Generative " + args.name
    else:
        tag = "generative-beta-" + short_sha
        title = "Generative beta " + short_sha
    if git("status", "--porcelain"):
        if not args.dry_run:
            fail("uncommitted changes; the release would not match the commit it tags")
        log(
            "uncommitted changes: this dry run is not what a release of this commit would contain"
        )

    check_pack()
    # Build before making OUT_DIR: dbt configures only when build/ is missing, so
    # an early build/beta-release/ would stop a fresh checkout being configured.
    built = build_firmware()
    os.makedirs(OUT_DIR, exist_ok=True)
    bin_path = os.path.join(OUT_DIR, tag + ".bin")
    pack_path = os.path.join(OUT_DIR, tag + "-pack.zip")
    shutil.copyfile(built, bin_path)
    zip_pack(sha, pack_path)
    log(f"built {bin_path} and {pack_path}")

    if args.dry_run:
        log("dry run: nothing published")
        return 0

    publish(tag, title, sha, [bin_path, pack_path])
    log(f"published {tag} on {FORK}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
